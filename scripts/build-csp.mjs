// يولّد CSP صارمة (بـ hashes) ويحقنها في dist/_headers مع COOP.
// يعمل بعد `astro build` وقبل النشر: node scripts/build-csp.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";
import { createHash } from "node:crypto";

const DIST = process.argv[2] || "dist";

const html = [];
(function walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) walk(p);
    else if (extname(p) === ".html") html.push(p);
  }
})(DIST);

// نطاقات السكربتات غير القابلة للتنفيذ (بيانات) لا تخضع لـ script-src
const DATA_TYPES = /^(application\/(ld\+json|json)|speculationrules|text\/(template|plain))$/i;

const hashes = new Set();
let inlineCount = 0;

for (const file of html) {
  const src = readFileSync(file, "utf8");
  const re = /<script([^>]*)>([\s\S]*?)<\/script>/gi;
  let m;
  while ((m = re.exec(src))) {
    const attrs = m[1] || "";
    if (/\bsrc\s*=/i.test(attrs)) continue;              // سكربت خارجي
    const typeMatch = attrs.match(/\btype\s*=\s*["']([^"']+)["']/i);
    const type = typeMatch ? typeMatch[1].trim() : "text/javascript";
    if (DATA_TYPES.test(type)) continue;                  // بيانات لا تُنفَّذ
    inlineCount++;
    const h = createHash("sha256").update(m[2], "utf8").digest("base64");
    hashes.add("'sha256-" + h + "'");
  }
}

const scriptSrc = ["'self'", ...hashes].join(" ");
const csp = [
  "default-src 'self'",
  `script-src ${scriptSrc}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'self'",
  "object-src 'none'",
  "upgrade-insecure-requests",
].join("; ");

const headersPath = join(DIST, "_headers");
let headers = readFileSync(headersPath, "utf8");

// إزالة أي بلوك سابق نولّده
headers = headers.replace(/\n# --- CSP \(generated\) ---[\s\S]*$/m, "");

headers += `
# --- CSP (generated by scripts/build-csp.mjs) ---
/*
  Content-Security-Policy: ${csp}
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
`;

writeFileSync(headersPath, headers.trimEnd() + "\n", "utf8");

// نسخة للمصدر لتبقى في المستودع
writeFileSync(
  "public/_headers.csp.txt",
  `# مولّد آليًا — انسخه إلى dist/_headers بعد البناء\nContent-Security-Policy: ${csp}\nCross-Origin-Opener-Policy: same-origin\nCross-Origin-Resource-Policy: same-origin\n`,
  "utf8"
);

console.log(`CSP: ${hashes.size} hash(es) from ${inlineCount} inline script(s) across ${html.length} page(s)`);
console.log(csp.slice(0, 200) + "…");
